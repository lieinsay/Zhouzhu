// 复用已有导出器的MSVC规格，在独立目录导出家具，不改主构建或历史快照。
import {readFileSync,writeFileSync,mkdirSync,existsSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {coreExportBuildSpec} from '../content-studio/model-export/build-core-export.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
if(process.argv.length!==4 || process.argv[2]!=='--output') throw new Error('用法：node tools/art-preview/export-furniture.mjs --output <新的版本目录>');
const output=path.resolve(process.argv[3]);
if(!output.startsWith(root+path.sep) || existsSync(output)) throw new Error('输出必须是仓库内尚不存在的新版本目录');
const cache=readFileSync(path.join(root,'cmake-build-debug/CMakeCache.txt'),'utf8');
const compiler=/^CMAKE_CXX_COMPILER:FILEPATH=(.+)$/m.exec(cache)?.[1].trim().replaceAll('\\','/');
const match=compiler?.match(/^(.*)\/VC\/Tools\/MSVC\/([^/]+)\/bin\/Hostx64\/x64\/cl.exe$/);
if(!match || !/^CMAKE_GENERATOR:INTERNAL=Ninja\r?$/m.test(cache) || !/^CMAKE_BUILD_TYPE:STRING=Debug\r?$/m.test(cache)) throw new Error('先核对Rider MSVC x64/Ninja/Debug缓存');
const rules=readFileSync(path.join(root,'cmake-build-debug/CMakeFiles/rules.ninja'),'utf8');
const language=/msvc_deps_prefix = Note: including file:/.test(rules)?'1033':/msvc_deps_prefix = 注意: 包含文件:/.test(rules)?'2052':null;
if(!language)throw new Error('无法匹配包含前缀');
const build=path.join(root,'build/art-furniture-export');mkdirSync(build,{recursive:true});
const spec=coreExportBuildSpec(root,build);
const args=spec.args.map(a=>a===path.join(root,'tools/content-studio/model-export/core-export.cpp')?path.join(root,'tools/art-preview/furniture-export.cpp'):a);
if(args.some(a=>/["\r\n]/.test(a)))throw new Error('编译参数含不支持的字符');
writeFileSync(path.join(build,'export.rsp'),args.map(a=>'"'+a+'"').join('\r\n'));
const vcvars=path.join(match[1],'VC/Auxiliary/Build/vcvars64.bat');
writeFileSync(path.join(build,'compile.cmd'),['@echo off','chcp 65001 >nul',`call "${vcvars}" -vcvars_ver=${match[2]}`,'if errorlevel 1 exit /b %errorlevel%',`set "VSLANG=${language}"`,'cl.exe @export.rsp','exit /b %errorlevel%'].join('\r\n'));
const built=spawnSync(process.env.ComSpec||'cmd.exe',['/d','/c','compile.cmd'],{cwd:build,encoding:'utf8',timeout:120000});
writeFileSync(path.join(build,'compile.log'),(built.stdout||'')+(built.stderr||''));
if(built.status!==0)throw new Error('家具导出器构建失败，见build/art-furniture-export/compile.log');
const exported=spawnSync(spec.output,[output],{encoding:'utf8',timeout:30000});
if(exported.status!==0)throw new Error('家具导出失败：'+exported.stderr);
process.stdout.write(exported.stdout);
